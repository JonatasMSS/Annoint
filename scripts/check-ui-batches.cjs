const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ win, page, waitFor, mouse, bounds, saved, exportedZip, pause }) => {
  const source = fs.readFileSync(path.join(__dirname, '..', 'test-images/valid/04-pequena.png')).toString('base64');
  const open = async (value) => {
    await page(`{window.confirm=()=>true;const transfer=new DataTransfer();transfer.items.add(new File([${JSON.stringify(JSON.stringify(value))}],'lotes.json',{type:'application/json'}));const input=document.querySelector('#project-input');input.files=transfer.files;document.querySelector('#toast').textContent='';input.dispatchEvent(new Event('change',{bubbles:true}));}`);
    await waitFor("document.querySelector('#toast').textContent.includes('Projeto aberto')");
    await saved();
  };
  const value = { version: 1, labels: [{ id: 'object', name: 'Objeto', color: '#2563eb' }], images: [{ id: 'first', name: 'frames/000.png', src: `data:image/png;base64,${source}`, width: 8, height: 8, annotations: [], reviewed: true }] };
  await open(value);
  console.log('Lotes: migração atômica e falha simulada');
  const beforeFailure = await page("import('./src/storage.js').then(m=>m.loadProject())");
  const failed = await page(`(async()=>{const original=IDBDatabase.prototype.transaction;IDBDatabase.prototype.transaction=function(stores,mode,...args){const tx=original.call(this,stores,mode,...args);if(Array.isArray(stores)&&stores.includes('assets')&&stores.includes('projects'))queueMicrotask(()=>tx.abort());return tx};try{await(await import('./src/storage.js')).externalizeProject(${JSON.stringify(value)},{commit:true});return 'erro não ocorreu'}catch(error){return error.message}finally{IDBDatabase.prototype.transaction=original}})()`);
  assert.match(failed, /projeto anterior foi preservado/);
  assert.deepEqual(await page("import('./src/storage.js').then(m=>m.loadProject())"), beforeFailure);
  await waitFor("document.querySelector('.image-surface > img').complete && document.querySelector('.image-surface > img').naturalWidth===8");
  await page(`{window.__liveUrls=new Set();window.__create=URL.createObjectURL;window.__revoke=URL.revokeObjectURL;URL.createObjectURL=function(blob){const url=window.__create(blob);window.__liveUrls.add(url);if(['application/json','application/zip'].includes(blob.type))window.__exported=blob;return url};URL.revokeObjectURL=function(url){window.__liveUrls.delete(url);window.__revoke(url)};const data=Uint8Array.from(atob(${JSON.stringify(source)}),c=>c.charCodeAt(0));const transfer=new DataTransfer();for(let i=1;i<=500;i++){const file=new File([data],String(i).padStart(3,'0')+'.png',{type:'image/png'});Object.defineProperty(file,'webkitRelativePath',{value:'frames/'+file.name});transfer.items.add(file)}const input=document.querySelector('#folder-input');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));}`);
  console.log('Lotes: importando 500 arquivos adicionais');
  await waitFor("document.querySelector('#batch-select')?.options.length===6", 90000);
  await waitFor("document.querySelectorAll('.thumbnail.image-loading').length===0");
  await saved();
  console.log('Lotes: 501 arquivos carregados');
  const local = await page("import('./src/storage.js').then(m=>m.loadProject())");
  assert.equal(local.images.length, 501);
  assert.ok(local.images.every((image) => image.src.startsWith('asset:')));
  assert.equal(await page("document.querySelectorAll('.thumbnail').length"), 100);
  assert.equal(await page('window.__liveUrls.size'), 100);
  assert.equal(await page("!!document.querySelector('.workspace-heading')"), false);
  await page("{for(const id of Array.from(document.querySelectorAll('.thumbnail'),e=>e.dataset.image)){document.querySelector('[data-image=\"'+id+'\"]').click();if(document.querySelector('.complete-button').getAttribute('aria-pressed')!=='true')document.querySelector('.complete-button').click()}}");
  assert.match(await page("document.querySelector('#batch-select').selectedOptions[0].textContent"), /100\/100.*Concluído/);
  console.log('Lotes: primeiro lote concluído');
  const selected = await page("document.querySelector('.thumbnail.active').dataset.image");
  await page("document.querySelector('#batch-select').value='5';document.querySelector('#batch-select').dispatchEvent(new Event('change',{bubbles:true}))");
  await waitFor("document.querySelectorAll('.thumbnail').length===1 && document.querySelectorAll('.thumbnail.image-loading').length===0");
  assert.equal(await page('window.__liveUrls.size'), 1);
  await page("document.querySelector('[data-tool=box]').click()");
  await win.webContents.capturePage();
  const rect = await bounds('.image-surface');
  mouse('mouseDown', rect.x + 2, rect.y + 2); await pause(30);
  mouse('mouseMove', rect.x + 6, rect.y + 6); await pause(30);
  mouse('mouseUp', rect.x + 6, rect.y + 6); await pause(80);
  await page("{for(const [key,value] of Object.entries({x:2,y:2,width:4,height:4})){const input=document.querySelector('#box-'+key);input.value=value;input.dispatchEvent(new Event('change',{bubbles:true}))}document.querySelector('.complete-button').click()}");
  await saved();
  assert.match(await page("document.querySelector('#batch-select').selectedOptions[0].textContent"), /1\/1.*Concluído/);
  console.log('Lotes: última imagem anotada');
  const height = await page("document.querySelector('#stage').clientHeight");
  await page("document.querySelector('[data-action=toggle-filmstrip]').click()");
  assert.equal(await page("document.querySelector('[data-action=toggle-filmstrip]').getAttribute('aria-expanded')"), 'false');
  assert.ok(await page("document.querySelector('#stage').clientHeight") > height);
  await page("document.querySelector('[data-action=previous-batch]').click();document.querySelector('[data-action=next-batch]').click();document.querySelector('[data-action=previous-batch]').click();document.querySelector('#batch-select').value='0';document.querySelector('#batch-select').dispatchEvent(new Event('change',{bubbles:true}))");
  await waitFor("document.querySelectorAll('.thumbnail.image-loading').length===0");
  assert.equal(await page("document.querySelector('.thumbnail.active').dataset.image"), selected);
  assert.equal(await page('window.__liveUrls.size'), 100);
  await page("window.__click=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){};document.querySelector('[data-action=export]').click();document.querySelector('#export-format').value='yolo';document.querySelector('#export-form').requestSubmit()");
  await waitFor("!document.querySelector('#export-dialog').open");
  const zip = await exportedZip();
  assert.equal(zip.size, 1004);
  assert.equal(zip.get('labels/frames/500.txt').toString(), '0 0.5 0.5 0.5 0.5\n');
  assert.deepEqual(zip.get('images/frames/500.png'), Buffer.from(source, 'base64'));
  await page("document.querySelector('[data-action=export]').click();document.querySelector('#export-format').value='json';document.querySelector('#export-form').requestSubmit()");
  await waitFor("!document.querySelector('#export-dialog').open");
  const portable = JSON.parse(await page('window.__exported.text()'));
  assert.equal(portable.images.length, 501);
  assert.ok(portable.images.every((image) => image.src.startsWith('data:')));
  assert.equal(portable.images.filter((image) => image.reviewed).length, 101);
  await page("HTMLAnchorElement.prototype.click=window.__click;document.querySelector('#batch-select').value='5';document.querySelector('#batch-select').dispatchEvent(new Event('change',{bubbles:true}))");
  await saved();
  await pause(100);
  console.log('Lotes: verificando reload e exclusão');
  const loaded = new Promise((resolve) => win.webContents.once('did-finish-load', resolve));
  win.reload(); await loaded;
  await waitFor("document.querySelector('#batch-select')?.value==='5'");
  assert.equal(await page("document.querySelector('#project-thumbnails').hidden"), true);
  assert.equal(await page("document.querySelector('.annotation').getAttribute('transform')"), 'translate(2 2)');
  await page("window.confirm=()=>false;document.querySelector('[data-action=delete-image]').click()");
  assert.equal((await page("import('./src/storage.js').then(m=>m.loadProject())")).images.length, 501);
  await page("window.confirm=()=>true;document.querySelector('[data-action=delete-image]').click()");
  await waitFor("document.querySelector('#batch-select').options.length===5"); await saved();
  assert.equal((await page("import('./src/storage.js').then(m=>m.loadProject())")).images.length, 500);
  assert.equal(await page("document.querySelector('[data-action=undo]').disabled"), true);
  await open(value);
  await page("document.querySelector('[data-action=delete-image]').click()");
  await waitFor("!!document.querySelector('.empty-editor')"); await saved();
  await open({ ...value, images: [] });
  await waitFor("!!document.querySelector('.empty-editor')");
  const emptyReload = new Promise((resolve) => win.webContents.once('did-finish-load', resolve));
  win.reload(); await emptyReload;
  await waitFor("!!document.querySelector('.empty-editor')");
  assert.equal(await page("document.querySelector('.progress-heading > span').textContent"), '0%');
  await open(value);
  console.log('OK: 501 arquivos, seis lotes, cache de no máximo100 URLs, conclusão, seleção/reload, recolher, exports completos e exclusão até vazio');
};
